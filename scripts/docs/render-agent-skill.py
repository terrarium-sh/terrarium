#!/usr/bin/env python3
"""Render skills/terra-box/SKILL.md from packaging/agent-skill.md and the docs it includes.

`--check` fails when the committed skill differs from a fresh render.
"""

import posixpath
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TEMPLATE = ROOT / "packaging/agent-skill.md"
SKILL = ROOT / "skills/terra-box/SKILL.md"
SITE_GUIDES = {"usage", "recipe", "manifest", "security", "sandboxing", "sandbox-policy"}
INCLUDE = re.compile(r"^<!-- include (docs/[\w.-]+\.md) -->$", re.M)
RELATIVE_LINK = re.compile(r"\]\((?![a-z]+:|#|/)([^)#]+)(#[^)]*)?\)")
NOTICE = (
    "<!-- Generated by scripts/docs/render-agent-skill.py from "
    "packaging/agent-skill.md and docs/. Edit those, then run `make skill`. -->"
)


def absolute_link(match, source_dir):
    path = posixpath.normpath(posixpath.join(source_dir, match[1]))
    anchor = match[2] or ""
    name = path.removeprefix("docs/").removesuffix(".md")
    if path.startswith("docs/") and name in SITE_GUIDES:
        return f"](https://terrarium.sh/docs/{name}/{anchor})"
    return f"](https://github.com/terrarium-sh/terrarium/blob/main/{path}{anchor})"


def demote_headings(markdown):
    lines, is_in_fence = [], False
    for line in markdown.splitlines():
        if line.startswith("```"):
            is_in_fence = not is_in_fence
        lines.append(f"#{line}" if not is_in_fence and line.startswith("#") else line)
    return "\n".join(lines)


def render_include(match):
    path = match[1]
    markdown = (ROOT / path).read_text().strip()
    linked = RELATIVE_LINK.sub(lambda link: absolute_link(link, posixpath.dirname(path)), markdown)
    return demote_headings(linked)


def render():
    _, frontmatter, body = TEMPLATE.read_text().split("---\n", 2)
    return f"---\n{frontmatter}---\n{NOTICE}\n{INCLUDE.sub(render_include, body)}"


def self_check():
    link = RELATIVE_LINK.search("[a](security.md#network)")
    assert absolute_link(link, "docs") == "](https://terrarium.sh/docs/security/#network)"
    link = RELATIVE_LINK.search("[b](../packaging/README.md#x)")
    assert absolute_link(link, "docs") == "](https://github.com/terrarium-sh/terrarium/blob/main/packaging/README.md#x)"
    assert RELATIVE_LINK.search("[c](https://x.y/a.md) [d](#e)") is None
    assert demote_headings("# A\n```sh\n# comment\n```\n## B") == "## A\n```sh\n# comment\n```\n### B"


def main():
    self_check()
    rendered = render()
    if sys.argv[1:] == ["--check"]:
        if not SKILL.exists() or SKILL.read_text() != rendered:
            raise SystemExit(f"{SKILL.relative_to(ROOT)} is stale: run `make skill`")
        return
    SKILL.parent.mkdir(parents=True, exist_ok=True)
    SKILL.write_text(rendered)


if __name__ == "__main__":
    main()
